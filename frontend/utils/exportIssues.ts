import { escapeCsvField, downloadFile } from "./exportAnalysis";
import type { IssueRecommendation } from "../types/api";

export type IssueExportFormat = "csv" | "markdown";

export interface IssueExportOptions {
  username?: string;
  date?: string;
}

/**
 * Escapes characters that break Markdown table syntax:
 * - Pipes '|' are escaped with backslash '\|'
 * - Line breaks are converted to spaces
 */
export function escapeMarkdownTableCell(value: string | number | null | undefined): string {
  if (value === null || value === undefined) {
    return "";
  }
  return String(value)
    .replace(/\|/g, "\\|")
    .replace(/[\r\n]+/g, " ")
    .trim();
}

/**
 * Calculates the display match score percentage for an issue.
 */
export function getIssueScore(issue: IssueRecommendation): number {
  return Math.round(issue.match_score ?? issue.score ?? 0);
}

/**
 * Formats a list of recommended issues into an RFC 4180-compliant CSV string.
 * Columns: Title, Repository, Link, Labels, Match Score.
 */
export function formatIssuesAsCsv(issues: IssueRecommendation[]): string {
  const lines: string[] = [];

  // CSV Header
  lines.push("Title,Repository,Link,Labels,Match Score");

  for (const issue of issues) {
    const title = escapeCsvField(issue.title || "");
    const repository = escapeCsvField(issue.repository || "");
    const link = escapeCsvField(issue.url || "");
    const labels = escapeCsvField((issue.labels || []).join(", "));
    const score = `${getIssueScore(issue)}%`;

    lines.push(`${title},${repository},${link},${labels},${score}`);
  }

  return lines.join("\r\n");
}

/**
 * Formats a list of recommended issues into a clean Markdown table report.
 * Includes Title, Repository, Labels, Match Score, and Link.
 */
export function formatIssuesAsMarkdown(
  issues: IssueRecommendation[],
  options?: IssueExportOptions
): string {
  const exportDate = options?.date || new Date().toISOString().split("T")[0];
  const userHeader = options?.username ? `**User**: @${options.username.trim()}\n` : "";

  const rows: string[] = [];

  if (issues && issues.length > 0) {
    for (const issue of issues) {
      const title = escapeMarkdownTableCell(issue.title || "");
      const repo = escapeMarkdownTableCell(issue.repository || "");
      const labels = escapeMarkdownTableCell((issue.labels || []).join(", ") || "-");
      const score = `${getIssueScore(issue)}%`;
      const link = issue.url ? `[View Issue](${issue.url})` : "-";

      rows.push(`| ${title} | ${repo} | ${labels} | ${score} | ${link} |`);
    }
  } else {
    rows.push("| No recommended issues found | - | - | - | - |");
  }

  return `# Recommended Open-Source Issues

${userHeader}**Export Date**: ${exportDate}
**Total Issues**: ${issues.length}

| Title | Repository | Labels | Match Score | Link |
| :--- | :--- | :--- | :---: | :--- |
${rows.join("\n")}

---
*Generated by [OpenSourceMate](https://github.com/Muskankr/OpenSourceMate) - AI-powered open-source contribution assistant.*
`;
}

/**
 * Generates a standardized export filename for recommended issues.
 */
export function getExportIssuesFilename(
  format: IssueExportFormat,
  username?: string,
  date?: string
): string {
  const dateStr = date || new Date().toISOString().split("T")[0];
  const sanitizedUser = username
    ? username
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9_-]/g, "")
    : "";
  const ext = format === "csv" ? "csv" : "md";

  if (sanitizedUser) {
    return `opensourcemate-recommended-issues-${sanitizedUser}-${dateStr}.${ext}`;
  }
  return `opensourcemate-recommended-issues-${dateStr}.${ext}`;
}

/**
 * Returns the MIME type corresponding to the chosen export format.
 */
export function getExportIssuesMimeType(format: IssueExportFormat): string {
  switch (format) {
    case "csv":
      return "text/csv;charset=utf-8";
    case "markdown":
      return "text/markdown;charset=utf-8";
  }
}

/**
 * Generates the exported file content and triggers browser download.
 */
export function exportRecommendedIssues(
  issues: IssueRecommendation[],
  format: IssueExportFormat,
  options?: IssueExportOptions
): void {
  const content =
    format === "csv" ? formatIssuesAsCsv(issues) : formatIssuesAsMarkdown(issues, options);
  const filename = getExportIssuesFilename(format, options?.username, options?.date);
  const mimeType = getExportIssuesMimeType(format);

  downloadFile(content, filename, mimeType);
}
